// Builds worker/catalog.js (the text the AI search understands) from public/tutorials.js.
// Runs automatically before every deploy (see "build" in wrangler.jsonc).
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const ctx = { window: {} };
vm.runInNewContext(readFileSync(new URL("../public/tutorials.js", import.meta.url), "utf8"), ctx);
const list = ctx.window.TUTORIALS.map(t => ({
  slug: t.slug,
  text: `${t.title}. ${t.summary} Topic: ${t.category}. Related: ${(t.tags || []).join(", ")}.`
}));
writeFileSync(new URL("../worker/catalog.js", import.meta.url),
  "// Generated by scripts/build-catalog.mjs. Do not edit by hand.\nexport default " + JSON.stringify(list, null, 0).replace(/},{/g, "},\n{") + ";\n");
console.log(`catalog: ${list.length} tutorials`);
